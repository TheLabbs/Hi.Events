def translate_complex_strings():
    with open('sv.po', 'r', encoding='utf-8') as f:
        content = f.read()
    
    empty_before = content.count('msgstr ""')
    print(f"Antal tomma översättningar före: {empty_before}")
    
    # Översätt alla komplexa strängar
    for english, swedish in complex_translations.items():
        escaped_english = re.escape(english)
        pattern = f'msgid "{escaped_english}"\nmsgstr ""'
        replacement = f'msgid "{english}"\nmsgstr "{swedish}"'
        content = re.sub(pattern, replacement, content)
    
    # Hantera HTML och komplexa meddelanden
    html_patterns = [
        (r'msgid "<0>Webhooks instantly notify external services when events happen, like adding a new attendee to your CRM or mailing list upon registration, ensuring seamless automation.</0><1>Use third-party services like <2>Zapier</2>, <3>IFTTT</3> or <4>Make</4> to create custom workflows and automate tasks.</1>"\nmsgstr ""',
         'msgid "<0>Webhooks instantly notify external services when events happen, like adding a new attendee to your CRM or mailing list upon registration, ensuring seamless automation.</0><1>Use third-party services like <2>Zapier</2>, <3>IFTTT</3> or <4>Make</4> to create custom workflows and automate tasks.</1>"\nmsgstr "<0>Webhooks meddelar omedelbart externa tjänster när händelser inträffar, som att lägga till en ny deltagare till ditt CRM eller e-postlista vid registrering, vilket säkerställer sömlös automatisering.</0><1>Använd tredjepartstjänster som <2>Zapier</2>, <3>IFTTT</3> eller <4>Make</4> för att skapa anpassade arbetsflöden och automatisera uppgifter.</1>"'),
    ]
    
    for pattern, replacement in html_patterns:
        content = content.replace(pattern, replacement)
    
    # Hantera placeholder-strängar med regex
    placeholder_patterns = [
        (r'msgid "\{(\w+)\} (\w+)"\nmsgstr ""', lambda m: f'msgid "{{{m.group(1)}}} {m.group(2)}"\nmsgstr "{{{m.group(1)}}} {complex_translations.get(m.group(2), m.group(2).lower())}"'),
        (r'msgid "(\d+) Active Webhook"\nmsgstr ""', r'msgid "\1 Active Webhook"\nmsgstr "\1 aktiv webhook"'),
        (r'msgid "(\d+) Active Webhooks"\nmsgstr ""', r'msgid "\1 Active Webhooks"\nmsgstr "\1 aktiva webhooks"'),
    ]
    
    for pattern, replacement in placeholder_patterns:
        content = re.sub(pattern, replacement, content)
    
    # Skriv tillbaka filen
    with open('sv.po', 'w', encoding='utf-8') as f:
        f.write(content)
    
    empty_after = content.count('msgstr ""')
    translated = empty_before - empty_after
    
    print(f"Antal tomma översättningar efter: {empty_after}")
    print(f"Översatte {translated} nya strängar")

if __name__ == "__main__":
    translate_complex_strings()
